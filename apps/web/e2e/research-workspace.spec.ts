const homeMetric=(page:Page,label:string)=>page.locator('.rd-kpis').getByRole('link',{name:new RegExp(label)}).locator('strong');
async function navigate(page:Page,label:'Home'|'Companies'|'Watchlist'|'Calendar'|'Saved'|'Notifications'){
 if(await page.locator('.rd-header').isVisible()){
  if(label==='Notifications')await page.locator('.rd-header').getByRole('link',{name:/^알림/}).click();
  else await page.getByRole('navigation',{name:'주 메뉴',exact:true}).getByRole('link',{name:{Home:'홈',Companies:'기업',Watchlist:'관심 기업',Calendar:'캘린더',Saved:'저장'}[label],exact:true}).click();
 }else if(await page.getByRole('navigation',{name:'Mobile navigation'}).isVisible()){
  const nav=page.getByRole('navigation',{name:'Mobile navigation'});
  if(label==='Saved'||label==='Notifications'||label==='Calendar'){
   await nav.getByRole('link',{name:'More',exact:true}).click();
   await main(page).getByRole('link',{name:label==='Saved'?'Saved items':label,exact:true}).click();
  }else await nav.getByRole('link',{name:label,exact:true}).click();
 }else if(label==='Notifications')await page.locator('.pc-topbar').getByRole('link',{name:/^Notifications/}).click();
 else await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:label,exact:true}).click();
}
async function screenshot(page:Page,info:TestInfo,name:string){
 await expect(page.locator('.pc-loading,.ws-loading,.m-loading')).toHaveCount(0);
 if(await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)>1){
  await page.screenshot({path:info.outputPath(`${name}-overflow.png`),fullPage:true,animations:'disabled'});
  await info.attach(`${name}-overflow-elements`,{contentType:'application/json',body:JSON.stringify(await page.evaluate(()=>[...document.querySelectorAll('body *')].map(node=>{const box=node.getBoundingClientRect();return {tag:node.tagName,class:node.className,left:box.left,right:box.right,width:box.width,text:node.textContent?.slice(0,90)};}).filter(box=>box.right>document.documentElement.clientWidth+1).slice(0,50)),null,2)});
 }
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth),'The workspace must fit the viewport').toBeLessThanOrEqual(1);
 await page.screenshot({path:info.outputPath(`research-workspace-${name}.png`),fullPage:true,animations:'disabled'});
}
